import { afterAll, beforeAll, describe, expect, it } from "vitest";
import type { FastifyInstance } from "fastify";
import { buildApp } from "../../src/app.js";
import { loadEnv } from "../../src/config/env.js";
import { createDb, type Database } from "../../src/db/client.js";

// Runs against a real, already-migrated local Postgres (DATABASE_URL from the environment
// — see backend/.env.example), the same way pgTAP and the concurrency scripts do. No mocks:
// this test exists specifically to prove the app can reach the real database, so mocking
// the database would defeat its purpose.

describe("GET /health", () => {
  let app: FastifyInstance;
  let db: Database;

  beforeAll(() => {
    const env = loadEnv();
    db = createDb(env);
    app = buildApp(env, db);
  });

  afterAll(async () => {
    await app.close();
    await db.destroy();
  });

  it("returns ok and confirms real database connectivity", async () => {
    const response = await app.inject({ method: "GET", url: "/health" });

    expect(response.statusCode).toBe(200);
    expect(response.json()).toEqual({ status: "ok", database: "ok" });
  });
});
