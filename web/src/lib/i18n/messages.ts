// All user-facing copy for both locales lives here. `fa` is typed against `en`, so a key that
// exists in one language but not the other is a compile error rather than a blank label.

export type Locale = "en" | "fa";

export const LOCALES: readonly Locale[] = ["en", "fa"];
export const DEFAULT_LOCALE: Locale = "en";
export const LOCALE_COOKIE = "bakhta_locale";

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "fa";
}

export function localeDir(locale: Locale): "ltr" | "rtl" {
  return locale === "fa" ? "rtl" : "ltr";
}

